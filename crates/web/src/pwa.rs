//! PWA assets generated from Rust: service worker script, registration snippet, and icon.
//!
//! The service worker and its registration are emitted from Rust so no handwritten JavaScript
//! application logic exists; they are generated artifacts of this module, versioned with the
//! application build so a new deployment activates cleanly without trapping running clients.

/// Current shell cache version; bumping it invalidates old caches on activation.
pub const SHELL_VERSION: &str = "2026-10-03";

/// Assets precached for the offline application shell.
pub const PRECACHE: &[&str] = &[
    "/",
    "/today",
    "/static/design.css",
    "/static/app.css",
    "/pkg/momentum-web.js",
    "/pkg/momentum-web_bg.wasm",
    "/manifest.webmanifest",
    "/static/icon.svg",
];

/// Generates the service worker script for a version.
#[must_use]
pub fn service_worker_script(version: &str) -> String {
    let precache = PRECACHE
        .iter()
        .map(|path| format!("\"{path}\""))
        .collect::<Vec<_>>()
        .join(",");
    format!(
        r#"// Generated by momentum-web::pwa; do not edit.
const SHELL_CACHE = "momentum-shell-{version}";
const PRECACHE = [{precache}];

self.addEventListener("install", (event) => {{
  event.waitUntil(
    caches.open(SHELL_CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
}});

self.addEventListener("activate", (event) => {{
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((key) => key !== SHELL_CACHE).map((key) => caches.delete(key))
      )
    ).then(() => self.clients.claim())
  );
}});

self.addEventListener("fetch", (event) => {{
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/sync") || url.pathname.startsWith("/api/")) return;
  if (url.pathname.startsWith("/static/") || url.pathname.startsWith("/pkg/")) {{
    event.respondWith(
      caches.match(request).then((cached) => cached || fetch(request).then((response) => {{
        const copy = response.clone();
        caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy));
        return response;
      }}))
    );
    return;
  }}
  event.respondWith(
    fetch(request)
      .then((response) => {{
        const copy = response.clone();
        caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy));
        return response;
      }})
      .catch(() => caches.match(request).then((cached) => cached || caches.match("/today")))
  );
}});
"#
    )
}

/// Registration and update-lifecycle snippet embedded in the document shell.
///
/// A new deployment installs, activates, and claims clients; the page reloads once on
/// controller change so running clients never stay on incompatible code.
pub const REGISTRATION_SNIPPET: &str = r#"(function () {
  if (!("serviceWorker" in navigator)) return;
  var reloaded = false;
  navigator.serviceWorker.addEventListener("controllerchange", function () {
    if (reloaded) return;
    reloaded = true;
    window.location.reload();
  });
  window.addEventListener("load", function () {
    navigator.serviceWorker.register("/service-worker.js").catch(function () {});
  });
})();"#;

