#[cfg(test)]
mod tests {
    use super::{service_worker_script, PRECACHE, REGISTRATION_SNIPPET, SHELL_VERSION};

    #[test]
    fn worker_script_is_versioned_and_precaches_the_shell() {
        let script = service_worker_script(SHELL_VERSION);
        assert!(script.contains(&format!("momentum-shell-{SHELL_VERSION}")));
        for asset in PRECACHE {
            assert!(script.contains(&format!("\"{asset}\"")), "missing {asset}");
        }
        assert!(script.contains("self.skipWaiting()"));
        assert!(script.contains("self.clients.claim()"));
        assert!(script.contains("caches.delete"));
        // Live data endpoints are never cached.
        assert!(script.contains("/sync"));
        assert!(script.contains("/api/"));
        // A different version produces an isolated cache name.
        assert!(!service_worker_script("other").contains(SHELL_VERSION));
    }

    #[test]
    fn registration_reloads_on_controller_change() {
        assert!(REGISTRATION_SNIPPET.contains("controllerchange"));
        assert!(REGISTRATION_SNIPPET.contains("register(\"/service-worker.js\")"));
        assert!(REGISTRATION_SNIPPET.contains("reloaded"));
    }
}
